"""Generate website accent tokens from the application's AccentColor asset."""
import json
from pathlib import Path

project = Path(__file__).resolve().parents[2]
asset = project / 'Sources/NornaStudio/Resources/Assets.xcassets/AccentColor.colorset/Contents.json'
colors = {}
for item in json.loads(asset.read_text())['colors']:
    appearances = {(entry['appearance'], entry['value']) for entry in item.get('appearances', [])}
    dark = ('luminosity', 'dark') in appearances
    contrast = ('contrast', 'high') in appearances
    channels = item['color']['components']
    colors[(dark, contrast)] = '#' + ''.join(f"{int(channels[key], 16):02x}" for key in ['red', 'green', 'blue'])
assert set(colors) == {(False, False), (True, False), (False, True), (True, True)}

def luminance(value):
    channels = [int(value[index:index + 2], 16) / 255 for index in [1, 3, 5]]
    channels = [channel / 12.92 if channel <= 0.04045 else ((channel + 0.055) / 1.055) ** 2.4 for channel in channels]
    return sum(channel * weight for channel, weight in zip(channels, [0.2126, 0.7152, 0.0722]))

def contrast(first, second):
    light, dark = sorted([luminance(first), luminance(second)], reverse=True)
    return (light + 0.05) / (dark + 0.05)

def tokens(dark, increased):
    accent = colors[(dark, increased)]
    text = max(['#ffffff', '#171719'], key=lambda color: contrast(accent, color))
    assert contrast(accent, text) >= 4.5
    return f'--accent:{accent};--accent-hover:{colors[(dark, True)]};--on-accent:{text};--accent-soft:color-mix(in srgb,var(--accent) {18 if dark else 10}%,var(--surface));'

css = '/* Generated by scripts/sync-theme.py from the project AccentColor asset. */\n'
css += ':root{' + tokens(False, False) + '}\n'
css += ':root[data-theme=dark]{' + tokens(True, False) + '}\n'
css += '@media(prefers-contrast:more){:root{' + tokens(False, True) + '}:root[data-theme=dark]{' + tokens(True, True) + '}}\n'
css += '''.primary{background:var(--accent);color:var(--on-accent)}
.primary:hover,.primary:active{background:var(--accent-hover);color:var(--on-accent)}
.hero-accent,.hero .eyebrow,.section-heading .eyebrow,.start-intro .eyebrow{color:var(--accent)}
.text-link,.source-download{color:var(--accent)}
.text-link:hover,.source-download:hover{color:var(--accent-hover)}
.brand-symbol{display:block;flex-shrink:0;width:28px;height:28px;background:var(--accent);-webkit-mask:url(assets/brand/symbol-mono.svg) center/contain no-repeat;mask:url(assets/brand/symbol-mono.svg) center/contain no-repeat}
.brand-symbol-large{width:36px;height:36px;margin-inline:auto}
.studio-app-icon{display:block;width:48px;height:48px;flex-shrink:0}
.studio-app-icon>img{display:block;width:48px;height:48px}
:root:not([data-theme=dark]) .studio-app-icon>[data-image-theme=dark],:root[data-theme=dark] .studio-app-icon>[data-image-theme=light]{display:none}
@media(max-width:760px){.brand .brand-symbol{width:24px;height:24px}}
'''
(project / 'website/dist/theme.css').write_text(css)
for (dark, increased), color in colors.items():
    print(f'{"dark" if dark else "light"}{" high contrast" if increased else ""}: {color}')
